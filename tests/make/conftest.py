def write_makefile(base_dir: Path, content: str, filename: str = "Makefile") -> Path:
    """Write a Makefile (or .mk include) into the given directory and return its path."""
    base_dir.mkdir(parents=True, exist_ok=True)
    makefile_path = base_dir / filename
    makefile_path.write_text(content)
    return makefile_path


