# Helper to run make with a completely controlled environment
def run_make(
    makefile_dir: Path,
    target: str,
    env: dict[str, str] | None = None,
    extra_args: list[str] | None = None,
    check: bool = False,
) -> subprocess.CompletedProcess[str]:
    """
    Run `make` in the given directory with a controlled environment.
    Returns the CompletedProcess so tests can inspect stdout/stderr/returncode.
    """
    env = env or {}
    full_env = os.environ.copy()
    # Strip any real container markers so tests start from a known "host" baseline
    for key in ("REMOTE_CONTAINERS", "CODESPACES", "XG_AIS_HOST_TYPE"):
        full_env.pop(key, None)
    full_env.update(env)

    cmd = ["make", "-C", str(makefile_dir), "-f", "Makefile", target]
    if extra_args:
        cmd.extend(extra_args)

    return subprocess.run(
        cmd,
        env=full_env,
        capture_output=True,
        text=True,
        check=check,
    )
